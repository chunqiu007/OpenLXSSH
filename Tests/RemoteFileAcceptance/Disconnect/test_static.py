class CoordinatorPrivateMetadataTests(unittest.TestCase):
    def setUp(self):
        # All generated bytes are synthetic metadata under THIS task's ignored .build.
        parent = HERE.parent / '.build'
        self.root = parent / ('atime-unit-' + str(uuid.uuid4()))
        self.root.mkdir(mode=0o700)
        self.directory = os.open(self.root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
        self.identity = os.fstat(self.directory)
        self.data = b'{"event":"synthetic-no-network"}\n'
        descriptor = os.open('metadata.json', os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600, dir_fd=self.directory)
        try:
            os.write(descriptor, self.data)
            os.fsync(descriptor)
        finally:
            os.close(descriptor)
        self.path = self.root / 'metadata.json'
        self.children = {'metadata.json'}

    def tearDown(self):
        try:
            current = os.stat(self.root, follow_symlinks=False)
            self.assertEqual((current.st_dev, current.st_ino), (self.identity.st_dev, self.identity.st_ino))
            self.assertEqual(current.st_uid, os.getuid())
            self.assertEqual(stat.S_IMODE(current.st_mode), 0o700)
            self.assertLessEqual(set(os.listdir(self.directory)), self.children)
            for name in self.children:
                try:
                    os.unlink(name, dir_fd=self.directory)
                except FileNotFoundError:
                    pass
        finally:
            os.close(self.directory)
        os.rmdir(self.root)

    @staticmethod
    def stable(info):
        return (info.st_dev, info.st_ino, info.st_uid, info.st_gid, info.st_mode,
                info.st_nlink, info.st_size, info.st_mtime_ns, info.st_ctime_ns)

    def test_real_delayed_first_read_allows_atime_only_change(self):
        before = self.path.stat()
        time.sleep(1.1)  # APFS atime granularity must cross a real second; no clock fakes.
        read = None
        try:
            read = coordinator.read_private(self.path)
        finally:
            after = self.path.stat()
            self.assertNotEqual(before.st_atime_ns, after.st_atime_ns)
            self.assertEqual(self.stable(before), self.stable(after))
        self.assertEqual(read, self.data)

    def _refuses_change_during_read(self, mutate):
        real_read = os.read
        def changed_read(descriptor, count):
            mutate()
            return real_read(descriptor, count)
        with patch.object(coordinator.os, 'read', side_effect=changed_read):
            with self.assertRaisesRegex(ValueError, '^changedMetadata$'):
                coordinator.read_private(self.path)

    def test_size_change_during_read_is_rejected(self):
        def mutate():
            descriptor = os.open('metadata.json', os.O_WRONLY | os.O_APPEND | os.O_NOFOLLOW, dir_fd=self.directory)
            try:
                os.write(descriptor, b'x')
            finally:
                os.close(descriptor)
        self._refuses_change_during_read(mutate)

    def test_mtime_change_during_read_is_rejected(self):
        before = self.path.stat()
        def mutate():
            os.utime(self.path, ns=(before.st_atime_ns, before.st_mtime_ns - 2_000_000_000), follow_symlinks=False)
            self.assertNotEqual(self.path.stat().st_mtime_ns, before.st_mtime_ns)
        self._refuses_change_during_read(mutate)

    def test_ctime_change_with_mode_restored_is_rejected(self):
        before = self.path.stat()
        time.sleep(.01)
        def mutate():
            os.chmod(self.path, 0o640, follow_symlinks=False)
            os.chmod(self.path, 0o600, follow_symlinks=False)
            after = self.path.stat()
            self.assertEqual(after.st_mode, before.st_mode)
            self.assertEqual(after.st_mtime_ns, before.st_mtime_ns)
            self.assertNotEqual(after.st_ctime_ns, before.st_ctime_ns)
        self._refuses_change_during_read(mutate)

    def test_hardlink_added_during_read_is_rejected(self):
        self.children.add('hardlink')
        self._refuses_change_during_read(lambda: os.link(self.path, self.root / 'hardlink', follow_symlinks=False))

    def test_permissions_changed_during_read_is_rejected(self):
        self._refuses_change_during_read(lambda: os.chmod(self.path, 0o640, follow_symlinks=False))

    def test_inode_swap_between_descriptor_samples_is_rejected(self):
        self.children.add('replacement')
        descriptor = os.open('replacement', os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600, dir_fd=self.directory)
        os.write(descriptor, self.data); os.close(descriptor)
        replacement = os.open('replacement', os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=self.directory)
        original_fstat = os.fstat
        samples = 0
        def changed_fstat(descriptor):
            nonlocal samples
            info = original_fstat(descriptor)
            if stat.S_ISREG(info.st_mode):
                samples += 1
                if samples == 2:
                    # Controlled test hook swaps the already-open descriptor for a REAL
                    # same-size/mode synthetic inode; no SSH or metadata is fabricated.
                    os.dup2(replacement, descriptor)
                    return original_fstat(descriptor)
            return info
        try:
            with patch.object(coordinator.os, 'fstat', side_effect=changed_fstat):
                with self.assertRaisesRegex(ValueError, '^changedMetadata$'):
                    coordinator.read_private(self.path)
        finally:
            os.close(replacement)
        self.assertEqual(samples, 2)

    def test_identity_comparison_retains_exact_security_fields(self):
        import types
        before = self.path.stat()
        names = ('st_dev', 'st_ino', 'st_uid', 'st_gid', 'st_mode', 'st_nlink', 'st_size', 'st_mtime_ns', 'st_ctime_ns')
        # Explicit unit boundary covers UID/GID/dev without chown or host changes.
        with patch.object(coordinator.os, 'fstat', wraps=os.fstat):
            self.assertEqual(coordinator.metadata_identity(before), tuple(getattr(before, name) for name in names))
        for name in names:
            values = {field: getattr(before, field) for field in names}
            values[name] += 1
            self.assertNotEqual(coordinator.metadata_identity(before), coordinator.metadata_identity(types.SimpleNamespace(**values)))


